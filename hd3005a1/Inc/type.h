/***************************************************************************************************
*程序结构
***************************************************************************************************/
#define DEAD_LOOP while(1)      /*!<while死循环定义*/

/*!<函数单次运行标志*/
#define ONCE_RUN(name, ret) {static bool name##_once_run = FALSE;\
    if (name##_once_run == TRUE) {return ret;} name##_once_run = TRUE;}

#define VOID_RET    /*!<空return*/

/***************************************************************************************************
*变参
***************************************************************************************************/
#include <stdarg.h>

