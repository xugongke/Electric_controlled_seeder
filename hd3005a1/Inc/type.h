/***************************************************************************************************
*\Def           Max
*\Description   返回两个参数中的较大值
*\Parameter     x   参数x
*\Parameter     y   参数y
*\Return        u8    两数中的较大值
***************************************************************************************************/
#define Max(x, y) ((x)<(y)?(y):(x))

/***************************************************************************************************
*\Def           Min
*\Description   返回两个参数中的较小值
*\Parameter     x   参数x
*\Parameter     y   参数y
*\Return        u8  两数中的较小值
***************************************************************************************************/
#define Min(x, y) ((x)<(y)?(x):(y))

/***************************************************************************************************
*\Def           Swap
*\Description   交换两个参数的值
*\Parameter     x   参数x
*\Parameter     y   参数y
*\Return        u8
***************************************************************************************************/
#define Swap(a, b) {(a)^=(b); (b)^=(a); (a)^=(b);}
